package com.piashcse.zodkmp.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.KSPLogger
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSType
import com.google.devtools.ksp.symbol.KSValueParameter

/**
 * Generates `ZodObjectSchema` definitions for classes annotated with
 * `@com.piashcse.zodkmp.ZodModel`.
 */
public class ZodModelProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger,
) : SymbolProcessor {
    private val generated = mutableSetOf<String>()

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val annotation = resolver.getSymbolsWithAnnotation(ZOD_MODEL)
        for (symbol in annotation) {
            if (symbol !is KSClassDeclaration) continue
            if (symbol.classKind != ClassKind.CLASS) {
                logger.error("@ZodModel can only be applied to classes", symbol)
                continue
            }
            val qualified = symbol.qualifiedName?.asString() ?: continue
            if (!generated.add(qualified)) continue
            generate(symbol)
        }
        return emptyList()
    }

    private fun generate(classDecl: KSClassDeclaration) {
        val constructor = classDecl.primaryConstructor
        if (constructor == null) {
            logger.error("@ZodModel classes need a primary constructor", classDecl)
            return
        }

        val packageName = classDecl.packageName.asString()
        val className = classDecl.simpleName.asString()
        val objectName = "${className}Zod"
        val strict =
            classDecl.annotations
                .firstOrNull { it.shortName.asString() == "ZodModel" }
                ?.arguments
                ?.firstOrNull { it.name?.asString() == "strict" }
                ?.value as? Boolean ?: false

        val rows = constructor.parameters.mapNotNull { parameter -> rowFor(parameter, classDecl) }
        if (rows.size != constructor.parameters.size) return

        val shapeLines = rows.joinToString("\n") { "            ${it.shape}" }
        val parserLines = rows.joinToString(",\n") { "                ${it.name} = ${it.parser}" }
        val strictCall = if (strict) "\n        .strict()" else ""

        val code =
            buildString {
                appendLine("// Generated by zodkmp-ksp. Do not edit.")
                appendLine("package $packageName")
                appendLine()
                appendLine("import com.piashcse.zodkmp.Zod")
                appendLine("import com.piashcse.zodkmp.ZodObjectSchema")
                appendLine("import com.piashcse.zodkmp.optional")
                appendLine()
                appendLine("public object $objectName {")
                appendLine("    public val schema: ZodObjectSchema<$className> =")
                appendLine("        Zod.objectSchema<$className>({")
                appendLine(shapeLines)
                appendLine("        }) { map ->")
                appendLine("            $className(")
                appendLine(parserLines)
                appendLine("            )")
                appendLine("        }$strictCall")
                appendLine("}")
            }

        val dependencies = Dependencies(aggregating = false, classDecl.containingFile!!)
        codeGenerator.createNewFile(dependencies, packageName, objectName, "kt").writer().use { it.write(code) }
    }

    private fun rowFor(
        parameter: KSValueParameter,
        owner: KSClassDeclaration,
    ): Row? {
        val name = parameter.name?.asString() ?: return null
        val type = parameter.type.resolve()
        val nullable = type.isMarkedNullable
        val declaration = type.declaration
        val classDecl = declaration as? KSClassDeclaration
        val qualified = declaration.qualifiedName?.asString()
        val isEnum = classDecl?.classKind == ClassKind.ENUM_CLASS
        val isModel = classDecl != null && classDecl.annotations.any { it.shortName.asString() == "ZodModel" }

        val (schema, parser) =
            when {
                isEnum -> {
                    val enumName = qualified!!.let { fullyQualifiedName(it) }
                    val accessor = if (nullable) "map[\"$name\"] as $enumName?" else "map[\"$name\"] as $enumName"
                    "Zod.enum($enumName::class)" to accessor
                }
                isModel -> {
                    val model = classDecl!!
                    val modelObject = "${model.simpleName.asString()}Zod"
                    val modelPackage = model.packageName.asString()
                    val schemaRef = if (modelPackage == owner.packageName.asString()) "$modelObject.schema" else "$modelPackage.$modelObject.schema"
                    val modelType =
                        if (modelPackage ==
                            owner.packageName.asString()
                        ) {
                            model.simpleName.asString()
                        } else {
                            "$modelPackage.${model.simpleName.asString()}"
                        }
                    schemaRef to (if (nullable) "map[\"$name\"] as $modelType?" else "map[\"$name\"] as $modelType")
                }
                qualified == "kotlin.String" ->
                    "Zod.string()" to (if (nullable) "map[\"$name\"] as String?" else "map[\"$name\"] as String")
                qualified == "kotlin.Boolean" ->
                    "Zod.boolean()" to (if (nullable) "map[\"$name\"] as Boolean?" else "map[\"$name\"] as Boolean")
                qualified == "kotlin.Int" ->
                    "Zod.number().int()" to (if (nullable) "(map[\"$name\"] as? Double)?.toInt()" else "(map[\"$name\"] as Double).toInt()")
                qualified == "kotlin.Long" ->
                    "Zod.long()" to (if (nullable) "map[\"$name\"] as Long?" else "map[\"$name\"] as Long")
                qualified == "kotlin.Double" ->
                    "Zod.number()" to (if (nullable) "map[\"$name\"] as Double?" else "map[\"$name\"] as Double")
                qualified == "kotlin.Float" ->
                    "Zod.number()" to (if (nullable) "(map[\"$name\"] as? Double)?.toFloat()" else "(map[\"$name\"] as Double).toFloat()")
                qualified == "kotlin.collections.List" ->
                    listRow(parameter, type, name, nullable, owner) ?: unsupported(parameter, type, name)
                else -> unsupported(parameter, type, name)
            }

        val effectiveSchema = if (nullable) "$schema.optional()" else schema
        val shape =
            if (nullable) {
                "field(\"$name\", $effectiveSchema)"
            } else {
                when (qualified) {
                    "kotlin.String" -> "string(\"$name\", $effectiveSchema)"
                    "kotlin.Boolean" -> "boolean(\"$name\", $effectiveSchema)"
                    "kotlin.Int", "kotlin.Double", "kotlin.Float" -> "number(\"$name\", $effectiveSchema)"
                    else -> "field(\"$name\", $effectiveSchema)"
                }
            }
        return Row(name, shape, parser)
    }

    private fun listRow(
        parameter: KSValueParameter,
        type: KSType,
        name: String,
        nullable: Boolean,
        owner: KSClassDeclaration,
    ): Pair<String, String>? {
        val element =
            type.arguments
                .firstOrNull()
                ?.type
                ?.resolve() ?: return null
        val elementDeclaration = element.declaration
        val elementClass = elementDeclaration as? KSClassDeclaration
        val elementQualified = elementDeclaration.qualifiedName?.asString()
        val isEnum = elementClass?.classKind == ClassKind.ENUM_CLASS
        val isModel = elementClass != null && elementClass.annotations.any { it.shortName.asString() == "ZodModel" }

        val (elementSchema, elementType, conversion) =
            when {
                isEnum -> {
                    val enumName = elementQualified!!
                    Triple("Zod.enum($enumName::class)", enumName, null)
                }
                isModel -> {
                    val model = elementClass!!
                    val modelObject = "${model.simpleName.asString()}Zod"
                    val modelPackage = model.packageName.asString()
                    val schemaRef = if (modelPackage == owner.packageName.asString()) "$modelObject.schema" else "$modelPackage.$modelObject.schema"
                    val modelType =
                        if (modelPackage ==
                            owner.packageName.asString()
                        ) {
                            model.simpleName.asString()
                        } else {
                            "$modelPackage.${model.simpleName.asString()}"
                        }
                    Triple(schemaRef, modelType, null)
                }
                elementQualified == "kotlin.String" -> Triple("Zod.string()", "String", null)
                elementQualified == "kotlin.Boolean" -> Triple("Zod.boolean()", "Boolean", null)
                elementQualified == "kotlin.Int" -> Triple("Zod.number().int()", "Double", ".map { it.toInt() }")
                elementQualified == "kotlin.Long" -> Triple("Zod.long()", "Long", null)
                elementQualified == "kotlin.Double" -> Triple("Zod.number()", "Double", null)
                elementQualified == "kotlin.Float" -> Triple("Zod.number()", "Double", ".map { it.toFloat() }")
                else -> {
                    logger.warn(
                        "Unsupported list element ${element.declaration.qualifiedName?.asString()} for '$name'; falling back to Zod.any()",
                        parameter,
                    )
                    Triple("Zod.any()", element.toString(), null)
                }
            }

        val parser =
            if (nullable) {
                "map[\"$name\"] as List<$elementType>?"
            } else {
                "(map[\"$name\"] as List<$elementType>)${conversion ?: ""}"
            }
        return "Zod.array($elementSchema)" to parser
    }

    private fun unsupported(
        parameter: KSValueParameter,
        type: KSType,
        name: String,
    ): Pair<String, String> {
        logger.warn(
            "Unsupported type ${type.declaration.qualifiedName?.asString()} for '$name'; falling back to Zod.any()",
            parameter,
        )
        return "Zod.any()" to "map[\"$name\"] as $type"
    }

    private fun fullyQualifiedName(name: String): String = name

    private data class Row(
        val name: String,
        val shape: String,
        val parser: String,
    )
}

public class ZodModelProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor = ZodModelProcessor(environment.codeGenerator, environment.logger)
}

private const val ZOD_MODEL = "com.piashcse.zodkmp.ZodModel"
